import { NextResponse } from 'next/server';

import { serverEnv } from '@/lib/env';
import { storage, usingLocalStorage } from '@/lib/storage';
import { verifyLocalSignature, type LocalSignaturePayload } from '@/lib/storage/local';

/**
 * The development and test stand-in for a storage provider's own endpoint.
 *
 * In production the browser PUTs to Cloudflare R2 and never touches this route,
 * which refuses to exist there. Locally it plays the provider's part so the
 * upload flow under test is the **real** three-step sequence — presign, direct
 * PUT, server-side verification — rather than a shortcut that only development
 * takes. A test that exercises a different flow from production tests nothing.
 *
 * It behaves like a provider on the points that matter:
 *
 *   - the signature authorises one key, one method, one content type, one
 *     maximum length, until one moment
 *   - an oversized or retyped body is refused here, not after the fact
 *   - the customer's own file is served as an attachment with `nosniff`, so a
 *     hostile SVG is downloaded rather than rendered — the same guarantee
 *     `presignGet` gets from the provider in production
 */

export const dynamic = 'force-dynamic';

function unavailable() {
  return NextResponse.json({ error: 'Not available.' }, { status: 404 });
}

function parseSignature(url: URL, method: 'PUT' | 'GET') {
  const key = url.searchParams.get('key');
  const expires = Number(url.searchParams.get('expires'));
  const signature = url.searchParams.get('signature');

  if (!key || !signature || !Number.isFinite(expires)) return null;

  const payload: LocalSignaturePayload = {
    key,
    method,
    expiresAt: expires,
    ...(method === 'PUT'
      ? {
          contentType: url.searchParams.get('contentType') ?? '',
          maxBytes: Number(url.searchParams.get('maxBytes') ?? 0),
        }
      : {}),
  };

  const valid = verifyLocalSignature(payload, signature, serverEnv.BETTER_AUTH_SECRET);
  return valid ? payload : null;
}

export async function PUT(request: Request) {
  // The gate is "is the filesystem adapter in use", which is false the moment
  // a bucket is configured — so this route disappears in production without
  // needing to reason about NODE_ENV.
  if (!usingLocalStorage()) return unavailable();

  const url = new URL(request.url);
  const payload = parseSignature(url, 'PUT');
  if (!payload) {
    return NextResponse.json({ error: 'Invalid or expired signature.' }, { status: 403 });
  }

  // The signature names a content type. A body sent as something else is not
  // the upload that was authorised.
  const contentType = request.headers.get('content-type')?.split(';')[0]?.trim();
  if (contentType !== payload.contentType) {
    return NextResponse.json({ error: 'Content type mismatch.' }, { status: 400 });
  }

  const body = new Uint8Array(await request.arrayBuffer());

  if (payload.maxBytes && body.byteLength > payload.maxBytes) {
    return NextResponse.json({ error: 'Too large.' }, { status: 413 });
  }

  await storage.put({
    key: payload.key,
    body,
    contentType: payload.contentType ?? 'application/octet-stream',
  });

  return new NextResponse(null, { status: 200 });
}

export async function GET(request: Request) {
  // The gate is "is the filesystem adapter in use", which is false the moment
  // a bucket is configured — so this route disappears in production without
  // needing to reason about NODE_ENV.
  if (!usingLocalStorage()) return unavailable();

  const url = new URL(request.url);
  const payload = parseSignature(url, 'GET');
  if (!payload) {
    return NextResponse.json({ error: 'Invalid or expired signature.' }, { status: 403 });
  }

  const body = await storage.get(payload.key);
  if (!body) return NextResponse.json({ error: 'Not found.' }, { status: 404 });

  /**
   * Two kinds of object, two dispositions.
   *
   * A **preview** is a JPEG this server generated by re-encoding the upload, so
   * its bytes are ours and it may render inline in the builder. The
   * **original** is customer-supplied and is always a download: an SVG served
   * as `image/svg+xml` from an origin carrying session cookies is a stored XSS,
   * so it goes out as an opaque attachment. Which one this is depends on
   * whether a download filename was signed into the URL, so a caller cannot
   * turn a download into a rendered document by editing a query string.
   */
  const requested = url.searchParams.get('filename');

  const disposition: Record<string, string> = requested
    ? {
        'content-type': 'application/octet-stream',
        'content-disposition': `attachment; filename="${requested.replace(/["\\\r\n]/g, '')}"`,
      }
    : { 'content-type': 'image/jpeg' };

  return new NextResponse(new Uint8Array(body), {
    status: 200,
    headers: {
      ...disposition,
      'x-content-type-options': 'nosniff',
      'cache-control': 'private, no-store',
    },
  });
}
